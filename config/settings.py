def _secret_key() -> str:
    """Return the secret key from the environment, or manage a local dev key.

    Priority:
        1. DJANGO_SECRET_KEY environment variable (preferred in production).
        2. A git-ignored `.secret_key` file in BASE_DIR (development only),
           generated on first run so no secret ever needs to be committed.
        3. An ephemeral per-process key if the filesystem is read-only.
    """
    from_env = os.environ.get("DJANGO_SECRET_KEY", "").strip()
    if from_env:
        return from_env

    key_file = BASE_DIR / ".secret_key"
    try:
        if key_file.exists():
            stored = key_file.read_text(encoding="utf-8").strip()
            if stored:
                return stored
        key = _stdlib_secrets.token_urlsafe(64)
        key_file.write_text(key, encoding="utf-8")
        return key
    except OSError:
        # Read-only filesystem: fall back to an ephemeral (per-process) key
        # rather than embedding a committed secret in the codebase.
        return _stdlib_secrets.token_urlsafe(64)


